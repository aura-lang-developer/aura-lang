    fn emit_import(&mut self, imp: &ImportDecl) {
        let mut items_str = Vec::new();
        for item in &imp.items {
            if let Some(ref alias) = item.alias {
                items_str.push(format!("{} as {}", item.name, alias));
            } else {
                items_str.push(item.name.clone());
            }
        }
        let source_js = if imp.source.starts_with("./") || imp.source.starts_with("../") {
            if imp.source.ends_with(".aura") {
                format!("{}.mjs", &imp.source[..imp.source.len() - 5])
            } else if !imp.source.ends_with(".js")
                && !imp.source.ends_with(".mjs")
                && !imp.source.ends_with(".json")
            {
                format!("{}.mjs", imp.source)
            } else {
                imp.source.clone()
            }
        } else if let Some(resolved) =
            crate::package::resolve_package_import(&imp.source, self.base_path.as_deref())
        {
            let mjs_path = resolved.with_extension("mjs");
            if let Some(ref base) = self.base_path {
                if let Ok(rel) = mjs_path.strip_prefix(base) {
                    format!("./{}", rel.display()).replace('\\', "/")
                } else if let Ok(cwd) = std::env::current_dir() {
                    if let Ok(rel) = mjs_path.strip_prefix(&cwd) {
                        format!("./{}", rel.display()).replace('\\', "/")
                    } else {
                        mjs_path.to_string_lossy().replace('\\', "/")
                    }
                } else {
                    mjs_path.to_string_lossy().replace('\\', "/")
                }
            } else if let Ok(cwd) = std::env::current_dir() {
                if let Ok(rel) = mjs_path.strip_prefix(&cwd) {
                    format!("./{}", rel.display()).replace('\\', "/")
                } else {
                    mjs_path.to_string_lossy().replace('\\', "/")
                }
            } else {
                mjs_path.to_string_lossy().replace('\\', "/")
            }
        } else {
            imp.source.clone()
        };
        let line = format!(
            "import {{ {} }} from \"{}\";",
            items_str.join(", "),
            source_js
        );
        self.write_line(&line);
        self.write_dts_line(&format!(
            "import {{ {} }} from \"{}\";",
            items_str.join(", "),
            imp.source
        ));
    }

