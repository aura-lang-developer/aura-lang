    pub fn ast_type_to_dts(&self, ty: &Type) -> String {
        match ty {
            Type::Named { name, type_args } => match name.as_str() {
                "Int" | "Float" | "Int8" | "Int16" | "Int32" | "Int64" | "Uint8" | "Uint16"
                | "Uint32" | "Uint64" | "Byte" | "Rune" | "Uintptr" | "Float32" | "Float64" => {
                    "number".to_string()
                }
                "String" => "string".to_string(),
                "Bool" => "boolean".to_string(),
                "Unit" => "void".to_string(),
                "Pointer" | "Ptr" => {
                    let inner = type_args
                        .first()
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    format!("Pointer<{}>", inner)
                }
                "Channel" | "Chan" => {
                    let inner = type_args
                        .first()
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    format!("Channel<{}>", inner)
                }
                "SendChannel" | "SendChan" => {
                    let inner = type_args
                        .first()
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    format!("SendChannel<{}>", inner)
                }
                "RecvChannel" | "RecvChan" => {
                    let inner = type_args
                        .first()
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    format!("RecvChannel<{}>", inner)
                }
                "WaitGroup" => "WaitGroup".to_string(),
                "List" | "Array" => {
                    if let Some(inner) = type_args.first() {
                        format!("Array<{}>", self.ast_type_to_dts(inner))
                    } else {
                        "Array<any>".to_string()
                    }
                }
                "Iterator" | "Interator" => {
                    if let Some(inner) = type_args.first() {
                        format!("Iterator<{}>", self.ast_type_to_dts(inner))
                    } else {
                        "Iterator<any>".to_string()
                    }
                }
                "Map" => {
                    let k_str = type_args
                        .first()
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    let v_str = type_args
                        .get(1)
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    format!("Map<{}, {}>", k_str, v_str)
                }
                "Set" => {
                    let elem_str = type_args
                        .first()
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    format!("Set<{}>", elem_str)
                }
                "Option" => {
                    if let Some(inner) = type_args.first() {
                        format!("({} | null | undefined)", self.ast_type_to_dts(inner))
                    } else {
                        "any".to_string()
                    }
                }
                "Result" => {
                    let ok_str = type_args
                        .first()
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    let err_str = type_args
                        .get(1)
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    format!(
                        "({{ readonly $: \"Ok\"; value: {} }} | {{ readonly $: \"Err\"; error: {} }})",
                        ok_str, err_str
                    )
                }
                "Task" => {
                    let ok_str = type_args
                        .first()
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    let _err_str = type_args
                        .get(1)
                        .map(|t| self.ast_type_to_dts(t))
                        .unwrap_or_else(|| "any".to_string());
                    format!("Promise<{}>", ok_str)
                }
                other => {
                    if type_args.is_empty() {
                        other.to_string()
                    } else {
                        let args_str = type_args
                            .iter()
                            .map(|t| self.ast_type_to_dts(t))
                            .collect::<Vec<_>>()
                            .join(", ");
                        format!("{}<{}>", other, args_str)
                    }
                }
            },
            Type::Record(fields) => {
                let fields_str = fields
                    .iter()
                    .map(|(n, t)| {
                        if n.ends_with('?') {
                            let clean_name = &n[..n.len() - 1];
                            format!("{}?: {}", clean_name, self.ast_type_to_dts(t))
                        } else {
                            format!("{}: {}", n, self.ast_type_to_dts(t))
                        }
                    })
                    .collect::<Vec<_>>()
                    .join("; ");
                format!("{{ {} }}", fields_str)
            }
            Type::Tuple(types) => {
                let types_str = types
                    .iter()
                    .map(|t| self.ast_type_to_dts(t))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("[{}]", types_str)
            }
            Type::Function {
                params,
                return_type,
            } => {
                let params_str = params
                    .iter()
                    .enumerate()
                    .map(|(i, p)| format!("arg{}: {}", i, self.ast_type_to_dts(p)))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("({}) => {}", params_str, self.ast_type_to_dts(return_type))
            }
            Type::Pointer(inner) => format!("Pointer<{}>", self.ast_type_to_dts(inner)),
            Type::SendChannel(inner) => format!("SendChannel<{}>", self.ast_type_to_dts(inner)),
            Type::RecvChannel(inner) => format!("RecvChannel<{}>", self.ast_type_to_dts(inner)),
            Type::Unit => "void".to_string(),
            Type::TypeVar(v) => v.clone(),
        }
    }

    fn emit_sum_type(&mut self, sum: &SumTypeDecl) {
        let export_kw = if sum.is_exported { "export " } else { "" };
        self.write_line(&format!("{}const {} = {{", export_kw, sum.name));
        self.indent_level += 1;

        let mut dts_variants = Vec::new();
        let mut dts_companion_fields = Vec::new();

        for variant in &sum.variants {
            match &variant.fields {
                VariantFields::Unit => {
                    self.write_line(&format!(
                        "{}: Object.freeze({{ $: \"{}\" }}),",
                        variant.name, variant.name
                    ));
                    dts_variants.push(format!("  | {{ readonly $: \"{}\" }}", variant.name));
                    dts_companion_fields.push(format!(
                        "  readonly {}: {{ readonly $: \"{}\" }}",
                        variant.name, variant.name
                    ));
                }
                VariantFields::Tuple(types) => {
                    let params: Vec<String> = (0..types.len()).map(|i| format!("_{}", i)).collect();
                    let params_str = params.join(", ");
                    let fields_str = params
                        .iter()
                        .map(|p| format!("{}: {}", p, p))
                        .collect::<Vec<_>>()
                        .join(", ");
                    self.write_line(&format!(
                        "{}: ({}) => Object.freeze({{ $: \"{}\", {} }}),",
                        variant.name, params_str, variant.name, fields_str
                    ));

                    let dts_tuple_fields = types
                        .iter()
                        .enumerate()
                        .map(|(i, t)| format!("_{}: {}", i, self.ast_type_to_dts(t)))
                        .collect::<Vec<_>>()
                        .join("; ");
                    let dts_sig_params = types
                        .iter()
                        .enumerate()
                        .map(|(i, t)| format!("_{}: {}", i, self.ast_type_to_dts(t)))
                        .collect::<Vec<_>>()
                        .join(", ");

                    dts_variants.push(format!(
                        "  | {{ readonly $: \"{}\"; {} }}",
                        variant.name, dts_tuple_fields
                    ));
                    dts_companion_fields.push(format!(
                        "  readonly {}: ({}) => {{ readonly $: \"{}\"; {} }}",
                        variant.name, dts_sig_params, variant.name, dts_tuple_fields
                    ));
                }
                VariantFields::Record(fields) => {
                    let field_names: Vec<String> = fields.iter().map(|(n, _)| n.clone()).collect();
                    let params_str = format!("{{ {} }}", field_names.join(", "));
                    let fields_str = field_names
                        .iter()
                        .map(|n| format!("{}: {}", n, n))
                        .collect::<Vec<_>>()
                        .join(", ");
                    self.write_line(&format!(
                        "{}: ({}) => Object.freeze({{ $: \"{}\", {} }}),",
                        variant.name, params_str, variant.name, fields_str
                    ));

                    let dts_rec_fields = fields
                        .iter()
                        .map(|(n, t)| format!("{}: {}", n, self.ast_type_to_dts(t)))
                        .collect::<Vec<_>>()
                        .join("; ");
                    let dts_sig_params = format!("args: {{ {} }}", dts_rec_fields);

                    dts_variants.push(format!(
                        "  | {{ readonly $: \"{}\"; {} }}",
                        variant.name, dts_rec_fields
                    ));
                    dts_companion_fields.push(format!(
                        "  readonly {}: ({}) => {{ readonly $: \"{}\"; {} }}",
                        variant.name, dts_sig_params, variant.name, dts_rec_fields
                    ));
                }
            }
        }

        self.indent_level -= 1;
        self.write_line("};\n");

        for variant in &sum.variants {
            self.write_line(&format!(
                "{}const {} = {}.{};",
                export_kw, variant.name, sum.name, variant.name
            ));
            if sum.is_exported {
                self.write_dts_line(&format!(
                    "export declare const {}: typeof {}.{};",
                    variant.name, sum.name, variant.name
                ));
            }
        }
        self.write_line("");

        if sum.is_exported {
            let type_params_str = if sum.type_params.is_empty() {
                String::new()
            } else {
                format!("<{}>", sum.type_params.join(", "))
            };
            self.write_dts_line(&format!(
                "export type {}{} = \n{};\n",
                sum.name,
                type_params_str,
                dts_variants.join("\n")
            ));
            self.write_dts_line(&format!(
                "export declare const {}: {{\n{}\n}};\n",
                sum.name,
                dts_companion_fields.join(";\n")
            ));
        }
    }

